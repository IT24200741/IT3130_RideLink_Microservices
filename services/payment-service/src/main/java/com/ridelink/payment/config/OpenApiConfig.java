import io.swagger.v3.oas.annotations.security.SecurityScheme;
import org.springframework.context.annotation.Configuration;

@Configuration
@OpenAPIDefinition(
        info = @Info(
                title = "Fare & Payment Service API",
                version = "1.0",
                description = "Handles fare calculation and payment processing for RideLink"
        )
)
@SecurityScheme(
        name = "bearerAuth",
        type = SecuritySchemeType.HTTP,
        scheme = "bearer",
        bearerFormat = "JWT",
        description = "Provide a valid JWT token. Example: Bearer eyJhbGci..."
)
public class OpenApiConfig {
}
